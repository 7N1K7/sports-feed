import fs from 'fs';
const out = [];
const f = await (await fetch('https://kickoff.kiwi/data/feed.json?x=' + Date.now())).json();
out.push('generated ' + f.generated);
const tri = f.events.filter(e => /tri|triangular/i.test(e.comp || ''));
for (const e of tri) out.push([e.startUTC, e.team, e.comp, e.home, 'v', e.away, e.status, e.result ? 'R:' + String(e.result).slice(0, 60) : '', e.broadcast || '-'].join(' | '));
for (const [k, v] of Object.entries(f.tables || {})) if (/tri/i.test(k)) out.push('TABLE ' + k + ' ' + JSON.stringify(v).slice(0, 700));
for (const k of Object.keys(f)) out.push('key ' + k + ' ' + (Array.isArray(f[k]) ? f[k].length : typeof f[k]));
const sc = f.events.filter(e => /Scotland/.test(e.home + e.away));
for (const e of sc) out.push(['SCOT', e.home, e.away, e.homeLogo || '', e.awayLogo || ''].join(' | '));
fs.writeFileSync(new URL('./out.txt', import.meta.url), out.join('\n'));
